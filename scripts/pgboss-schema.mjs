#!/usr/bin/env node
// Prints the SQL that creates the pg-boss schema, for environments where the application's
// database role has no DDL rights (JOBS_AUTO_MIGRATE=false). Save it as a migration:
//
//   pnpm db:new pgboss_schema          # prints the new file name, e.g. 0003_pgboss_schema.sql
//   pnpm --silent jobs:schema-sql > db/migrations/0003_pgboss_schema.sql
//
// The output starts with "-- migrate:no-transaction" because the SQL manages its own
// transaction.
//
// After a pg-boss upgrade, print the upgrade SQL from the installed schema version:
//   pnpm --silent jobs:schema-sql --from <version>
import { getConstructionPlans, getMigrationPlans } from 'pg-boss';

const args = process.argv.slice(2);
const option = (name) => {
  const index = args.indexOf(name);
  return index === -1 ? undefined : args[index + 1];
};
const schema = option('--schema') ?? 'pgboss';
const from = option('--from');

const sql =
  from === undefined ? getConstructionPlans(schema) : getMigrationPlans(schema, Number(from));
process.stdout.write(
  `-- migrate:no-transaction\n-- Generated by scripts/pgboss-schema.mjs (schema "${schema}"). Do not edit.\n${sql}\n`,
);
